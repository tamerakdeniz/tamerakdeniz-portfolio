import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const BASE = 'http://localhost:3100';
const DB = 'http://127.0.0.1:9000';
const NS = 'demo-portfolio-default-rtdb';
const out = 'artifacts/editors';
await mkdir(out, { recursive: true });
const results = [];
const record = (name) => { results.push({ name, pass: true }); console.log('PASS', name); };
const db = async (path, method = 'GET', body) => { const r = await fetch(`${DB}/${path}.json?ns=${NS}`, { method, headers: { Authorization: 'Bearer owner', 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }); assert.equal(r.status, 200); return r.json(); };
const until = async (get, test, label) => { const end = Date.now() + 15000; while (Date.now() < end) { const value = await get(); if (test(value)) return value; await new Promise((r) => setTimeout(r, 200)); } throw new Error(`Timed out: ${label}`); };
const list = (v) => Object.values(v || {});
const browser = await chromium.launch({ channel: 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: 'artifacts/cms-lifecycle/admin-session.json' });
await context.route(/https:\/\/(?:[^/]*firebase[^/]*|identitytoolkit.googleapis.com|generativelanguage.googleapis.com)\//, (r) => r.abort());
const page = await context.newPage();
const errors = []; page.on('pageerror', (error) => errors.push(error.message));
const nav = (name) => page.locator('aside').getByRole('button', { name: new RegExp(name) }).click();
const save = async () => { const done = page.waitForResponse((r) => r.url().endsWith('/api/revalidate') && r.request().method() === 'POST'); await page.getByRole('button', { name: 'Save', exact: true }).click(); assert.equal((await done).status(), 200); };
const text = async (route) => (await fetch(BASE + route)).text();
const stamp = Date.now();
try {
  // This suite owns only synthetic biography/CV fixtures in the fixed demo emulator.
  await db('', 'PATCH', { 'siteData/aboutEntries': [], 'siteData/activeAboutId': '', 'siteData/cvFiles': [], 'siteData/activeCvId': '' });
  await page.goto(BASE + '/admin');
  await nav('Timeline');
  for (const [type, ongoing] of [['education', false], ['work', true], ['certification', false], ['achievement', false]]) {
    await page.getByRole('button', { name: /Add New/ }).click();
    await page.getByLabel('Type', { exact: true }).selectOption(type);
    await page.getByLabel('Title (EN)', { exact: true }).fill(`Synthetic ${type} ${stamp}`);
    await page.getByLabel('Title (TR)', { exact: true }).fill(`Sentetik ${type} ${stamp}`);
    await page.getByLabel('Company (EN)', { exact: true }).fill('Test Institution');
    await page.getByLabel('Company (TR)', { exact: true }).fill('Test Kurumu');
    await page.getByLabel('Description (EN)', { exact: true }).fill('Synthetic verification entry, not personal history.');
    await page.getByLabel('Description (TR)', { exact: true }).fill('Kişisel geçmiş olmayan sentetik doğrulama kaydı.');
    await page.getByLabel('Start date', { exact: true }).fill('2024-01');
    await page.getByLabel('Ongoing', { exact: true }).setChecked(ongoing);
    if (!ongoing) await page.getByLabel('End date', { exact: true }).fill('2025-06');
    await page.getByLabel('Institution or credential URL', { exact: true }).fill('https://example.org/credential');
    await save();
    assert.ok(list(await db('siteData/timeline')).some((entry) => entry.title.en === `Synthetic ${type} ${stamp}` && entry.startDate === '2024-01' && (entry.current ?? false) === ongoing));
  }
  const resume = await text('/resume');
  for (const type of ['education','work','certification','achievement']) assert.ok(resume.includes(`Synthetic ${type} ${stamp}`));
  assert.ok(resume.includes('Jan 2024') && resume.includes('Present') && resume.includes('Jun 2025'));
  assert.ok((await text('/about')).includes(`Synthetic education ${stamp}`));
  record('Timeline UI: all four types, bilingual fields, structured dates, ongoing, URLs and public propagation');
  await nav('Skills');
  await page.getByRole('button', { name: /Add New/ }).click();
  await page.getByLabel('Name', { exact: true }).fill(`SyntheticSkill${stamp}`);
  await page.getByLabel('New category', { exact: true }).fill('systems-test');
  await page.getByLabel('New category', { exact: true }).press('Enter');
  await page.getByLabel('Published', { exact: true }).uncheck();
  await save();
  assert.ok(list(await db('siteDrafts/skills')).some((skill) => skill.name === `SyntheticSkill${stamp}` && skill.category.includes('systems-test') && skill.id));
  assert.ok(!(await text('/resume')).includes(`SyntheticSkill${stamp}`));
  const skillRow = page.locator('[draggable=true]').filter({ hasText: `SyntheticSkill${stamp}` });
  await skillRow.hover();
  await skillRow.getByTitle('Publish', { exact: true }).click();
  await until(() => text('/resume'), (v) => v.includes(`SyntheticSkill${stamp}`), 'published skill');
  record('Skills UI: custom category, stable ID, private draft, publication and recruiter propagation');
  await nav('About');
  await page.getByRole('button', { name: /Add New/ }).click();
  await page.getByLabel('Title (EN)', { exact: true }).fill('Synthetic biography');
  await page.getByLabel('Title (TR)', { exact: true }).fill('Sentetik biyografi');
  await page.getByLabel('Content (EN)', { exact: true }).fill('Synthetic biography created through the content editor.');
  await page.getByLabel('Content (TR)', { exact: true }).fill('İçerik düzenleyicisinden oluşturulan sentetik biyografi.');
  await save();
  assert.ok((await text('/about')).includes('Synthetic biography created'));
  record('About UI: bilingual biography reaches About and shared public content');
  await nav('Profile & display');
  await page.getByLabel('Full display name', { exact: true }).fill('CMS Verified Operator');
  await page.getByLabel('Short display name', { exact: true }).fill('CMS Verified');
  await page.getByLabel('Professional role (EN)', { exact: true }).fill('Synthetic Verification Engineer');
  await page.getByLabel('Professional role (TR)', { exact: true }).fill('Sentetik Doğrulama Mühendisi');
  await page.locator('summary').filter({ hasText: 'Field journal photo' }).click();
  await page.getByLabel(/Upload file|Replace/).setInputFiles('artifacts/cms-lifecycle/mobile.png');
  await page.getByRole('progressbar').waitFor({ state: 'hidden' });
  await page.getByLabel('Alternative text (EN)', { exact: true }).fill('Synthetic test portrait swatch');
  await page.getByLabel('Alternative text (TR)', { exact: true }).fill('Sentetik test portre görseli');
  await save();
  const home = await text('/');
  assert.ok(home.includes('CMS Verified Operator') && home.includes('Synthetic Verification Engineer'));
  assert.ok(home.includes('<title>CMS Verified Operator'));
  assert.ok((await db('siteData/profile')).fieldPhoto.path);
  record('Profile UI: bilingual identity and uploaded field photo reach public markup and metadata');
  await nav('CV');
  await page.getByLabel('Upload PDF', { exact: false }).setInputFiles('public/demo/resume.pdf');
  await page.getByRole('progressbar').waitFor({ state: 'hidden' });
  await until(() => db('siteData/cvFiles'), (v) => list(v).length > 0, 'PDF persisted');
  await page.getByLabel('Document language', { exact: false }).first().selectOption('en');
  const cv = list(await until(() => db('siteData/cvFiles'), (v) => list(v).some((f) => f.language === 'en'), 'CV language'))[0];
  const download = await fetch(`${BASE}/api/download-cv?url=${encodeURIComponent(cv.dataUrl)}`);
  assert.equal(download.status, 200); assert.match(download.headers.get('content-type'), /application\/pdf/);
  assert.ok(download.headers.get('content-disposition').includes('attachment'));
  assert.equal((await fetch(`${BASE}/api/download-cv?url=${encodeURIComponent('https://firebasestorage.googleapis.com/v0/b/unknown/o/arbitrary.pdf')}`)).status, 404);
  record('CV UI: actual PDF upload, language selection, registered download; arbitrary proxy request rejected');
  await nav('Settings');
  await page.getByRole('button', { name: 'Scan unused media', exact: true }).click();
  await page.getByText('No eligible unused files found.', { exact: true }).waitFor();
  record('Orphan scan completes against real emulator Storage and protects fresh uploads');
  await page.screenshot({ path: `${out}/settings-en.png`, fullPage: true });
  await page.getByRole('button', { name: 'TR', exact: true }).click();
  assert.ok(!(await page.locator('body').innerText()).match(/\badmin-[a-z-]+/));
  await page.screenshot({ path: `${out}/settings-tr.png`, fullPage: true });
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await nav('Profile & display');
  const snapshot = await db('siteData/profile');
  await page.getByLabel('Full display name', { exact: true }).fill('SHOULD NOT PERSIST');
  const rules = JSON.parse(await readFile('database.rules.json', 'utf8'));
  const denied = structuredClone(rules); denied.rules.siteData['.write'] = false;
  await db('.settings/rules', 'PUT', denied);
  try {
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByText('Permission denied. Check your admin access and Firebase rules.', { exact: true }).waitFor();
    assert.deepEqual(await db('siteData/profile'), snapshot);
    assert.equal(await page.getByLabel('Full display name', { exact: true }).inputValue(), 'SHOULD NOT PERSIST');
    assert.equal((await fetch(snapshot.fieldPhoto.url)).status, 200);
  } finally { await db('.settings/rules', 'PUT', rules); }
  record('Failed real database update leaves stored content/media intact and retains unsaved form');
  assert.deepEqual(errors, []);
} catch (error) { results.push({ name: error.message, pass: false }); await page.screenshot({ path: `${out}/failure.png`, fullPage: true }).catch(() => {}); console.error(error); process.exitCode = 1; }
finally { await writeFile(`${out}/results.json`, JSON.stringify({ results, errors }, null, 2)); await browser.close(); }

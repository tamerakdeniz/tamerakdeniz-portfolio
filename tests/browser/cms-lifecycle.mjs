const until = async (get, predicate, label, timeout = 12000) => {
  const end = Date.now() + timeout;
  while (Date.now() < end) { const value = await get(); if (predicate(value)) return value; await new Promise((r) => setTimeout(r, 200)); }
  throw new Error(`Timed out: ${label}`);
};
